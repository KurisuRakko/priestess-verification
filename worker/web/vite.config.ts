import { fileURLToPath } from "node:url";

import react from "@vitejs/plugin-react";
import { defineConfig } from "vite";

/**
 * The Worker's browser front end: one React bundle per page family.
 *
 *   showcase  →  `/`                               (src/showcase/main.tsx)
 *   gate      →  the gate page and `/protected`    (src/gate/main.tsx)
 *   admin     →  `/admin` and `/admin/callback`    (src/admin/main.tsx)
 *
 * `npm run build:web` (web/build.mjs) builds each entry on its own into exactly
 * one classic script + one stylesheet, `src/generated/<entry>.client.js` and
 * `src/generated/<entry>.css`, which `demo-page.js`, `gate-page.js` and
 * `admin/page.js` inline.
 * Nothing is fetched at runtime: no code splitting, no external fonts (the
 * gate's CSP is `default-src 'none'`), assets inlined.
 *
 * Rakko Design comes from the vendor copy, aliased by absolute path like
 * RakkoDashboard does; `vendor/rakko-design/` is generated by
 * `scripts/sync-design.sh` and never edited by hand. `tsconfig.json`'s `paths`
 * mirror these aliases (tsc does not read this file).
 */
const vendor = (rel: string) =>
  fileURLToPath(new URL(`../../vendor/rakko-design/${rel}`, import.meta.url));

const VENDOR_REACT = /[\\/]vendor[\\/]rakko-design[\\/]react[\\/]src[\\/]/;

// `wrangler dev` (npm run dev) — the Vite dev server proxies everything the
// pages talk to, so `npm run dev:web` gives hot reload against real endpoints.
// PV_DEV_WORKER / PV_DEV_PORT point a second, throwaway dev server elsewhere
// (e.g. at a `wrangler dev --port 8788` for headless screenshots); unset, the
// defaults below apply.
const WORKER = process.env.PV_DEV_WORKER || "http://127.0.0.1:8787";
const PORT = Number(process.env.PV_DEV_PORT) || 5198;
const PROXIED = [
  "/widget.js",
  "/cap_wasm_bg.wasm",
  "/hashwx.wasm",
  "/pako_inflate.min.js",
  "/mascot",
  "/demo",
  "/__gate",
];

export default defineConfig({
  root: fileURLToPath(new URL(".", import.meta.url)),
  plugins: [react()],
  resolve: {
    // Array form matches in order: `/styles.css` must come before the bare name.
    alias: [
      {
        find: "@rakko/react/styles.css",
        replacement: vendor("react/src/styles.css"),
      },
      { find: "@rakko/react", replacement: vendor("react/src/index.ts") },
      {
        find: "@rakko/design-system/tokens.css",
        replacement: vendor("tokens.generated.css"),
      },
      // Extensionless, so tsc finds the sibling `.d.ts` (see tsconfig.json).
      {
        find: "@rakko/design-system/ripple",
        replacement: vendor("design-system/src/ripple"),
      },
      {
        find: "@rakko/design-system/context-action",
        replacement: vendor("design-system/src/context-action"),
      },
    ],
    // Also lets the vendor copy (outside worker/, with no node_modules in
    // reach) resolve these from worker/node_modules.
    dedupe: ["react", "react-dom", "@base-ui/react"],
  },
  build: {
    target: "es2022",
    // Everything ends up inline in the HTML; a separate asset file would need
    // a route (and a CSP exception) of its own.
    assetsInlineLimit: Number.POSITIVE_INFINITY,
    cssCodeSplit: false,
    modulePreload: false,
    reportCompressedSize: false,
    rolldownOptions: {
      // The vendor copy has no package.json (`"sideEffects": false`), so
      // without this every primitive @rakko/react exports would be kept
      // whether a page uses it or not. Its CSS still always loads (styles.css).
      treeshake: {
        moduleSideEffects: (id: string) =>
          !(VENDOR_REACT.test(id) && /\.tsx?$/.test(id)),
      },
    },
  },
  server: {
    host: "127.0.0.1",
    port: PORT,
    // Reached through `tailscale serve` for previews on the tailnet.
    allowedHosts: ["rakkoserver.tail524041.ts.net"],
    strictPort: true,
    // The Worker's same-origin checks (/__gate/pass, /demo/siteverify) compare
    // Origin with its own URL, so proxied requests carry the Worker's origin.
    proxy: Object.fromEntries(
      PROXIED.map((path) => [
        path,
        {
          target: WORKER,
          changeOrigin: true,
          configure: (proxy) => {
            proxy.on("proxyReq", (req) => {
              if (req.getHeader("origin")) req.setHeader("origin", WORKER);
            });
          },
        },
      ]),
    ),
  },
});
